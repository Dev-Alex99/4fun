// Disposable loopback-only TURN/UDP fault lab. Production deployment uses coturn.
// Run with: npm exec --yes --package=node-turn@0.0.6 -- node scripts/turn-node-lab.mjs --local
import { createSocket } from 'node:dgram';
import { createRequire } from 'node:module';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { delimiter, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomBytes } from 'node:crypto';
import { createInterface } from 'node:readline';

if (!process.argv.includes('--local')) throw new Error('This disposable relay requires --local and binds only 127.0.0.1.');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const envPath = resolve(root, '.env.turn-node-lab.local');
const statusDir = resolve(root, 'infra/turn/.runtime');
mkdirSync(statusDir, { recursive: true });
const marker = '# Generated by scripts/turn-node-lab.mjs; local-only temporary credentials.';
if (existsSync(envPath) && !readFileSync(envPath, 'utf8').startsWith(marker)) throw new Error('Refusing to overwrite an unrelated environment file.');
const require = createRequire(import.meta.url);
let Turn;
for (const path of (process.env.PATH || '').split(delimiter)) {
  const manifest = resolve(path, '../node-turn/package.json');
  if (!existsSync(manifest)) continue;
  const pkg = JSON.parse(readFileSync(manifest, 'utf8'));
  if (pkg.name === 'node-turn' && pkg.version === '0.0.6') { Turn = require(resolve(dirname(manifest), pkg.main)); break; }
}
if (!Turn) throw new Error('Run via npm exec --yes --package=node-turn@0.0.6 -- node scripts/turn-node-lab.mjs --local');

const username = `lab-${randomBytes(8).toString('hex')}`, credential = randomBytes(24).toString('base64url');
const server = new Turn({ listeningPort: 3479, listeningIps: ['127.0.0.1'], relayIps: ['127.0.0.1'],
  minPort: 49200, maxPort: 49279, authMech: 'long-term', realm: 'tp04-node-lab.local',
  credentials: { [username]: credential }, maxAllocateLifetime: 1200, defaultAllocatetLifetime: 600,
  debugLevel: 'OFF', debug: () => {} });

// Every browser<->TURN leg traverses this proxy. A peer round trip traverses four
// legs. These are encrypted UDP datagrams, before WebRTC/SCTP retransmission.
const profiles = {
  baseline: { rttMs: 0, jitterMs: 0, loss: 0 },
  mild: { rttMs: 100, jitterMs: 20, loss: 0.01 },
  moderate: { rttMs: 200, jitterMs: 60, loss: 0.05 },
  severe: { rttMs: 350, jitterMs: 100, loss: 0.10 }
};
let active = 'baseline', seed = 20261022, outageUntil = 0, stopped = false, profileTimer;
let counters = { received: 0, dropped: 0, forwarded: 0, queuePeak: 0 };
const timers = new Set(), links = new Map(), front = createSocket('udp4');
function random() { seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0; return seed / 4294967296; }
function forward(socket, packet, port) {
  counters.received++;
  const profile = profiles[active];
  if (Date.now() < outageUntil || random() < profile.loss || timers.size >= 2048) { counters.dropped++; return; }
  const delay = Math.max(0, profile.rttMs / 4 + (random() * 2 - 1) * profile.jitterMs / 2);
  const timer = setTimeout(() => {
    timers.delete(timer);
    if (!stopped) socket.send(packet, port, '127.0.0.1', error => { if (!error) counters.forwarded++; });
  }, delay);
  timers.add(timer); counters.queuePeak = Math.max(counters.queuePeak, timers.size);
}
front.on('error', error => { console.error(`TURN lab UDP: ${error.code || error.message}`); stop(1); });
front.on('message', (packet, remote) => {
  if (remote.address !== '127.0.0.1' || stopped) return;
  let upstream = links.get(remote.port);
  if (!upstream) {
    if (links.size >= 64) return;
    upstream = createSocket('udp4'); links.set(remote.port, upstream);
    upstream.on('error', error => { console.error(`TURN lab upstream: ${error.code || error.message}`); });
    upstream.on('message', response => forward(front, response, remote.port));
    upstream.bind(0, '127.0.0.1');
  }
  forward(upstream, packet, 3479);
});
function status() {
  const report = { kind: 'udp-profile', profile: active, ...profiles[active], seed,
    outageRemainingMs: Math.max(0, outageUntil - Date.now()), endpoints: links.size, ...counters,
    actualLossPercent: counters.received ? +(100 * counters.dropped / counters.received).toFixed(2) : 0,
    queued: timers.size };
  writeFileSync(resolve(statusDir, 'node-proxy-status.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
}
function stop(code = 0) {
  if (stopped) return;
  stopped = true; status();
  clearTimeout(profileTimer);
  for (const timer of timers) clearTimeout(timer);
  for (const socket of links.values()) { try { socket.close(); } catch {} }
  try { front.close(); } catch {}
  try { server.stop(); } catch {}
  // node-turn allocations own timers too. This process is the disposable boundary.
  setTimeout(() => process.exit(code), 50).unref();
  process.exitCode = code;
}
process.on('SIGINT', () => stop()); process.on('SIGTERM', () => stop());
server.start();
front.bind(3478, '127.0.0.1', () => {
  writeFileSync(envPath, `${marker}\nVITE_RTC_ICE_TRANSPORT_POLICY=relay\nVITE_RTC_ICE_SERVERS='${JSON.stringify([{ urls: 'turn:127.0.0.1:3478?transport=udp', username, credential }])}'\n`, { mode: 0o600 });
  console.log('Local authenticated TURN ready on 127.0.0.1:3478; expires when stopped or after 20 minutes.');
  console.log('Run Vite with --mode turn-node-lab. Commands: baseline | mild | moderate | severe [delayMs] | outage [ms] | stats | stop.');
  status();
});
const lines = createInterface({ input: process.stdin });
lines.on('line', line => {
  const [command, arg] = line.trim().split(/\s+/);
  if (command in profiles) {
    clearTimeout(profileTimer);
    const change = () => { active = command; seed = 20261022; outageUntil = 0; counters = { received: 0, dropped: 0, forwarded: 0, queuePeak: 0 }; status(); };
    const delay = Number(arg || 0);
    if (!Number.isFinite(delay) || delay < 0 || delay > 60000) { console.log('Invalid profile delay.'); return; }
    if (delay) { profileTimer = setTimeout(change, delay); console.log(`Profile ${command} scheduled in ${delay} ms.`); return; }
    change(); return;
  }
  else if (command === 'outage') { const ms = Number(arg || 3000); if (Number.isFinite(ms) && ms >= 0 && ms <= 15000) outageUntil = Date.now() + ms; }
  else if (command === 'stop') { stop(); return; }
  else if (command !== 'stats') { console.log('Unknown command.'); return; }
  status();
});
setTimeout(() => stop(), 20 * 60 * 1000).unref();
