#!/usr/bin/env node
import { createHash, createHmac, randomBytes } from 'node:crypto';
import { existsSync, lstatSync, mkdirSync, readFileSync, renameSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const turnDir = join(root, 'infra', 'turn');
const runtime = join(turnDir, '.runtime');
const configFile = join(runtime, 'turnserver.conf');
const secretFile = join(runtime, 'auth-secret');
const stateFile = join(runtime, 'state.json');
const envFile = join(root, '.env.turn-lab.local');
const composeFile = join(turnDir, 'compose.lab.yml');
const owner = createHash('sha256').update(root.toLowerCase()).digest('hex').slice(0, 12);
const project = `tp04-turn-lab-${owner}`;
const container = `${project}-turn`;
const network = `${project}_default`;
const ownerLabel = 'io.tp04.turn-lab.owner';
const envMarker = `# Generated by scripts/turn-lab.mjs; owner=${owner}`;
const image = 'coturn/coturn:4.18.0-r0';
const ttlSeconds = 3600;

function fail(message) { throw new Error(message); }
function run(command, args, options = {}) {
  const result = spawnSync(command, args, { cwd: root, encoding: 'utf8', windowsHide: true, timeout: 20000, ...options });
  if (result.error) fail(`${command}: ${result.error.code === 'ENOENT' ? 'no está instalado o no está en PATH.' : result.error.message}`);
  return result;
}
function docker(args, options = {}) { return run('docker', args, options); }
function composeEnv() {
  return { ...process.env, TURN_LAB_OWNER: owner, TURN_LAB_CONTAINER_NAME: container,
    TURN_LAB_RUNTIME_DIR: runtime.replaceAll('\\', '/'),
    TURN_LAB_UID: String(process.getuid?.() ?? 65534), TURN_LAB_GID: String(process.getgid?.() ?? 65534) };
}
function compose(args, options = {}) {
  return docker(['compose', '--project-name', project, '--project-directory', turnDir, '--file', composeFile, ...args],
    { env: composeEnv(), ...options });
}
function requireDocker() {
  if (docker(['compose', 'version']).status !== 0) fail('Instala Docker Compose v2 o posterior antes de usar este laboratorio.');
  let info;
  try { info = docker(['info', '--format', '{{.OSType}}']); }
  catch { fail('El daemon Docker no respondió a tiempo. Abre Docker Desktop en modo Linux, espera a que inicie y repite el comando. No se inició TURN.'); }
  if (info.status !== 0) fail('Docker está instalado pero el daemon no responde. Abre Docker Desktop, espera a que inicie y activa contenedores Linux; después repite el comando. No se inició TURN.');
  if (info.stdout.trim() !== 'linux') fail('Este laboratorio requiere el motor de contenedores Linux de Docker Desktop.');
}
function inspect(kind, name) {
  const result = docker([kind, 'inspect', name]);
  if (result.status !== 0) {
    if (/No such (object|container|network)/i.test(result.stderr)) return null;
    fail(`No se pudo inspeccionar ${kind} ${name}: ${result.stderr.trim()}`);
  }
  return JSON.parse(result.stdout)[0];
}
function owned(resource) {
  const labels = resource.Config?.Labels ?? resource.Labels ?? {};
  if (labels[ownerLabel] !== owner) fail('Existe un recurso Docker con el nombre reservado del laboratorio pero sin su etiqueta de propiedad. No se modificó.');
  return resource;
}
function noSymlink(path) {
  if (existsSync(path) && lstatSync(path).isSymbolicLink()) fail(`Se rechaza una ruta simbólica para datos del laboratorio: ${path}`);
}
function readManagedState() {
  for (const path of [runtime, stateFile, secretFile, configFile, envFile]) noSymlink(path);
  if (!existsSync(stateFile)) return null;
  const state = JSON.parse(readFileSync(stateFile, 'utf8'));
  if (state.owner !== owner || state.schemaVersion !== 1) fail('Los datos runtime pertenecen a otra instalación; no se sobrescribieron.');
  return state;
}
function assertManagedEnv() {
  noSymlink(envFile);
  if (existsSync(envFile) && !readFileSync(envFile, 'utf8').startsWith(`${envMarker}\n`)) {
    fail('Ya existe .env.turn-lab.local y no fue creado por este laboratorio. Consérvalo fuera de esta ruta antes de iniciar; no se sobrescribió.');
  }
}
function writePrivate(path, content) {
  noSymlink(path);
  const temporary = `${path}.${randomBytes(6).toString('hex')}.tmp`;
  try {
    writeFileSync(temporary, content, { mode: 0o600, flag: 'wx' });
    renameSync(temporary, path);
  } finally { if (existsSync(temporary)) unlinkSync(temporary); }
}
function withLifecycleLock(operation) {
  noSymlink(runtime);
  mkdirSync(runtime, { recursive: true, mode: 0o700 });
  const lock = join(runtime, 'lifecycle.lock');
  try { writeFileSync(lock, `${JSON.stringify({ owner, pid: process.pid })}\n`, { flag: 'wx', mode: 0o600 }); }
  catch (error) {
    if (error.code === 'EEXIST') fail(`Otra operación del laboratorio tiene el bloqueo ${lock}. Espera a que termine; si el proceso se interrumpió, verifica su PID antes de retirar sólo ese bloqueo.`);
    throw error;
  }
  try { operation(); } finally { unlinkSync(lock); }
}
function credentials(secret, expiresAt = Math.floor(Date.now() / 1000) + ttlSeconds, username) {
  const name = username ?? `${expiresAt}:tp04-${randomBytes(6).toString('hex')}`;
  return { username: name, credential: createHmac('sha1', secret).update(name).digest('base64'), expiresAt };
}
function renderConfig(secret) {
  if (!/^[a-f0-9]{64}$/.test(secret)) fail('El secreto runtime debe contener 32 bytes aleatorios en hexadecimal.');
  return readFileSync(join(turnDir, 'turnserver.lab.conf.template'), 'utf8').replace('${TURN_SHARED_SECRET}', secret);
}
function makeEnv(auth) {
  const ice = [{ urls: ['turn:127.0.0.1:3478?transport=udp', 'turn:127.0.0.1:3478?transport=tcp'],
    username: auth.username, credential: auth.credential }];
  return `${envMarker}\n# Credenciales temporales; caducan ${new Date(auth.expiresAt * 1000).toISOString()}. No publicar.\nVITE_RTC_ICE_SERVERS='${JSON.stringify(ice)}'\nVITE_RTC_ICE_TRANSPORT_POLICY=relay\n`;
}
function validate() {
  const secret = randomBytes(32).toString('hex');
  const config = renderConfig(secret);
  const yml = readFileSync(composeFile, 'utf8');
  const assert = (condition, message) => { if (!condition) fail(`Validación: ${message}`); };
  assert(config.includes('use-auth-secret\n') && !/^no-auth/m.test(config), 'se requiere autenticación.');
  assert(config.includes('realm=tp04.local\n') && config.includes('cli=false\n') && config.includes('web-admin=false\n'), 'realm o administración incorrectos.');
  assert(config.includes('min-port=49160\n') && config.includes('max-port=49179\n'), 'rango de relay inesperado.');
  assert(config.includes('allow-loopback-peers\n') && config.includes('allowed-peer-ip=127.0.0.1\n'), 'excepción local incorrecta.');
  assert(!config.includes('${') && !/^\s*-\s*["']?0\.0\.0\.0:/m.test(yml), 'plantilla incompleta o puerto público.');
  assert(yml.includes(`image: ${image}`), 'la imagen no coincide con la versión fijada.');
  const ports = [...yml.matchAll(/^\s+- "([^"\n]+)"$/gm)].map(match => match[1]);
  assert(ports.length === 3 && ports.every(port => port.startsWith('127.0.0.1:')), 'todos los puertos deben estar limitados a loopback.');
  assert(makeEnv(credentials(secret)).includes('VITE_RTC_ICE_TRANSPORT_POLICY=relay'), 'falta política relay.');
  return { image, container, project, envFile, runtime, credentialTtlSeconds: ttlSeconds,
    listeners: ['127.0.0.1:3478/udp', '127.0.0.1:3478/tcp'], relayPorts: '127.0.0.1:49160-49179/udp' };
}
function assertIgnored() {
  for (const path of [secretFile, configFile, stateFile, envFile]) {
    if (run('git', ['check-ignore', '--quiet', '--', path]).status !== 0) fail(`La ruta de credenciales no está ignorada por Git: ${path}. No se escribieron secretos.`);
  }
}
function prepareCredentials(existingContainer) {
  assertManagedEnv();
  assertIgnored();
  const state = readManagedState();
  if (existingContainer && (!state || !existsSync(secretFile) || !existsSync(configFile))) {
    fail('El contenedor existe pero faltan sus datos runtime. Ejecuta stop y vuelve a iniciar; no se rotó su secreto en vivo.');
  }
  if (!state && [secretFile, configFile].some(existsSync)) fail('Hay archivos runtime sin estado de propiedad. Consérvalos antes de iniciar; no se sobrescribieron.');
  mkdirSync(runtime, { recursive: true, mode: 0o700 });
  const secret = state ? readFileSync(secretFile, 'utf8').trim() : randomBytes(32).toString('hex');
  const reusable = state && state.expiresAt > Math.floor(Date.now() / 1000) + 300;
  const auth = reusable ? credentials(secret, state.expiresAt, state.username) : credentials(secret);
  writePrivate(secretFile, `${secret}\n`);
  writePrivate(configFile, renderConfig(secret));
  writePrivate(stateFile, `${JSON.stringify({ schemaVersion: 1, owner, username: auth.username, expiresAt: auth.expiresAt }, null, 2)}\n`);
  writePrivate(envFile, makeEnv(auth));
  return auth;
}
function start() {
  requireDocker();
  const existing = inspect('container', container);
  if (existing) owned(existing);
  const oldNetwork = inspect('network', network);
  if (oldNetwork) owned(oldNetwork);
  const auth = prepareCredentials(existing);
  if (!existing?.State?.Running || existing.State.Health?.Status !== 'healthy') {
    console.log(`Iniciando únicamente ${container} con ${image} (puede descargar la imagen oficial).`);
    const result = compose(['up', '--detach', '--no-deps', '--wait', '--wait-timeout', '30', 'turn'], { stdio: 'inherit', timeout: 180000 });
    if (result.status !== 0) fail('Docker Compose no pudo iniciar TURN. Los archivos temporales se conservaron para diagnóstico; no se afirmó una conexión relay.');
  }
  const active = inspect('container', container);
  if (!active || !owned(active).State?.Running || active.State.Health?.Status !== 'healthy') fail('TURN no quedó ejecutándose con su listener TCP saludable. Revisa docker logs del contenedor del laboratorio.');
  console.log(`Contenedor y listener TCP saludables; aún requiere verificar el par ICE relay/relay y el tráfico en el navegador.\nEntorno Vite: ${envFile}\nCredenciales válidas hasta ${new Date(auth.expiresAt * 1000).toISOString()}.\nArranca Vite con --mode turn-lab (o reinícialo para recargar el entorno).`);
}
function status() {
  requireDocker();
  const item = inspect('container', container);
  if (item) owned(item);
  const state = readManagedState();
  console.log(JSON.stringify({ container, running: Boolean(item?.State?.Running), status: item?.State?.Status ?? 'not-created', health: item?.State?.Health?.Status ?? null,
    envFile: existsSync(envFile) ? envFile : null, credentialsExpireAt: state ? new Date(state.expiresAt * 1000).toISOString() : null,
    credentialsExpired: state ? state.expiresAt <= Math.floor(Date.now() / 1000) : null }, null, 2));
}
function stop(purge) {
  requireDocker();
  const item = inspect('container', container);
  if (item) {
    owned(item);
    if (item.State?.Running && docker(['container', 'stop', '--time', '5', item.Id]).status !== 0) fail('No se pudo detener el contenedor del laboratorio.');
    if (docker(['container', 'rm', '--volumes', item.Id]).status !== 0) fail('No se pudo retirar el contenedor detenido.');
  }
  const net = inspect('network', network);
  if (net) {
    owned(net);
    if (Object.keys(net.Containers ?? {}).length === 0 && docker(['network', 'rm', net.Id]).status !== 0) fail('No se pudo retirar la red vacía del laboratorio.');
  }
  if (purge) {
    assertManagedEnv();
    const state = readManagedState();
    if (!state && [secretFile, configFile, envFile].some(existsSync)) fail('No existe evidencia de propiedad runtime para borrar esos archivos; se conservaron.');
    for (const path of [secretFile, configFile, stateFile, envFile]) if (existsSync(path)) unlinkSync(path);
  }
  console.log(`Laboratorio detenido; no se tocaron otros contenedores. ${purge ? 'Se borraron sus credenciales temporales.' : 'Credenciales temporales conservadas; stop --purge las elimina.'}`);
}
function main() {
  const [action = 'help', ...flags] = process.argv.slice(2);
  const allowed = { start: ['--local', '--dry-run'], validate: ['--docker-config'], status: [], stop: ['--purge'], help: [], '--help': [] };
  if (!Object.hasOwn(allowed, action) || flags.some(flag => !allowed[action].includes(flag))) fail('Acción u opción desconocida. Usa help.');
  if (action === 'help' || action === '--help') {
    console.log('TURN local de prueba (sin instalación pública)\n  node scripts/turn-lab.mjs validate [--docker-config]\n  node scripts/turn-lab.mjs start --local [--dry-run]\n  node scripts/turn-lab.mjs status\n  node scripts/turn-lab.mjs stop [--purge]\nEl secreto compartido nunca se imprime ni se envía al frontend.');
    return;
  }
  const plan = validate();
  if (action === 'validate') {
    if (flags.includes('--docker-config')) {
      const result = compose(['config', '--quiet']);
      if (result.status !== 0) fail(`Docker Compose rechazó la configuración: ${result.stderr.trim()}`);
    }
    console.log('Plantillas, autenticación, TTL y puertos loopback validados. No se inició ningún contenedor.');
  } else if (action === 'start') {
    if (!flags.includes('--local')) fail('El arranque requiere --local explícito. Esta configuración permite peers loopback y nunca debe publicarse.');
    if (flags.includes('--dry-run')) { console.log(JSON.stringify({ ...plan, dryRun: true, filesWritten: false, containersStarted: false }, null, 2)); return; }
    withLifecycleLock(start);
  } else if (action === 'status') status();
  else if (action === 'stop') withLifecycleLock(() => stop(flags.includes('--purge')));
  else fail('Acción desconocida. Usa help.');
}
try { main(); } catch (error) { console.error(`TURN lab: ${error.message}`); process.exitCode = 1; }
